_DEV_DIGITS = "".join(chr(0x0966 + i) for i in range(10))
_D = "[0-9" + _DEV_DIGITS + "]"
# "10,000", "1,23,456", "1,234,567", but not "3,5"
_THOUSANDS = re.compile(f"(?<!{_D})(?:{_D}{{1,3}}(?:,{_D}{{2}})*,{_D}{{3}}|{_D}{{1,3}}(?:,{_D}{{3}})+)(?!,?{_D})")


def cardinal(n):
    if n < 100:
        return _BELOW_100[n]
    if n < 1000:
        hundreds, rest = divmod(n, 100)
        return _BELOW_100[hundreds] + " सौ" + (" " + _BELOW_100[rest] if rest else "")
    value, word = next(item for item in _HIGH if n >= item[0])
    quotient, rest = divmod(n, value)
    return cardinal(quotient) + " " + word + (" " + cardinal(rest) if rest else "")


def normalize_hi_numbers_before(text):
    # before punctuation is stripped
    text = _THOUSANDS.sub(lambda m: m.group().replace(",", ""), text)
    return text.replace("%", " प्रतिशत ")


def normalize_hi_numbers_after(text):
    to_ascii = {ord(d): str(i) for i, d in enumerate(_DEV_DIGITS)}
    text = re.sub(_D + "+", lambda m: " " + cardinal(int(m.group().translate(to_ascii))) + " ", text)
    return " ".join(_VARIANTS.get(token, token) for token in text.split())
